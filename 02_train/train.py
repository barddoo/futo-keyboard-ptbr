"""
Training script for KeyboardLM (language picked by KEYBOARD_LANG, default pt).

Runs on any CUDA or ROCm GPU. ROCm (AMD) uses the same torch.cuda API —
PyTorch on ROCm maps 'cuda' device calls to HIP automatically.

Usage:
    # On AMD GPU machine (ROCm + PyTorch for ROCm installed):
    python3 train.py

    # Override checkpoint dir:
    python3 train.py --out /path/to/checkpoints
"""
import argparse
import os
import time
import math
from pathlib import Path

import torch
from torch.optim import AdamW
from torch.optim.lr_scheduler import CosineAnnealingLR

# Add project root to path
import sys
sys.path.insert(0, str(Path(__file__).parent.parent))

from model import KeyboardLM, ModelConfig
from dataset import make_loader
from langs import load as load_lang

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------
LANG = load_lang()
PROCESSED_DIR = LANG.processed_dir
SP_MODEL = LANG.sp_model

# Correction-format training data (generated by 01_data/make_correction_data.py
# from the plain corpus). Falls back to plain text if it hasn't been generated.
CORRECTION_DATA = PROCESSED_DIR / "correction_train.txt"
TRAIN_DATA = CORRECTION_DATA if CORRECTION_DATA.exists() else PROCESSED_DIR / "train.txt"

DEFAULT_OUT = LANG.checkpoint_dir

TRAIN_CONFIG = dict(
    # Small batch on purpose: the loss is computed over batch*seq*vocab logits
    # (cross_entropy upcasts to fp32), and 64x256x16000 keeps peak VRAM under
    # 24 GB even for the 512-embd / 8-layer model.
    batch_size=64,
    max_seq_len=256,
    lr=4e-4,              # sqrt LR scaling from baseline 3e-4
    min_lr=1e-5,
    weight_decay=0.1,
    grad_clip=1.0,
    epochs=3,             # full corpus (4.7M samples); fewer epochs than before
    log_every=100,
    save_every=10000,     # keep checkpoint clutter down on the bigger model
    warmup_steps=500,
    bf16=True,            # RDNA3 has fast bf16; ~2x throughput vs fp32
)

# Overrides for smoke tests / small-memory machines (e.g. Apple Silicon, where
# the default batch needs far more unified memory than a laptop has):
#   KEYBOARD_BATCH_SIZE=8 KEYBOARD_MAX_STEPS=300 python3 02_train/train.py
if os.environ.get("KEYBOARD_BATCH_SIZE"):
    TRAIN_CONFIG["batch_size"] = int(os.environ["KEYBOARD_BATCH_SIZE"])
# 0 = no limit; otherwise stop after this many optimizer steps (validation
# and best.pt are still written).
MAX_STEPS = int(os.environ.get("KEYBOARD_MAX_STEPS", "0"))

# ~42M params, same scale as the official FUTO ml4 model (512 embd, 8 layers).
MODEL_CONFIG = ModelConfig(
    vocab_size=16_000,
    n_layer=8,
    n_head=8,
    n_embd=512,
    max_seq_len=256,
    dropout=0.1,
)


def get_device() -> torch.device:
    if torch.cuda.is_available():
        # Works for NVIDIA CUDA and AMD ROCm
        dev = torch.device("cuda")
        print(f"GPU: {torch.cuda.get_device_name(0)}")
    elif torch.backends.mps.is_available():
        # Apple Silicon (M1/M2/M3/M4) — Metal Performance Shaders
        dev = torch.device("mps")
        print("GPU: Apple Metal (MPS)")
    else:
        dev = torch.device("cpu")
        print("WARNING: No GPU found, training on CPU will be very slow")
    return dev


def cosine_lr(step: int, warmup: int, total: int, max_lr: float, min_lr: float) -> float:
    if step < warmup:
        return max_lr * step / warmup
    progress = (step - warmup) / max(total - warmup, 1)
    return min_lr + 0.5 * (max_lr - min_lr) * (1 + math.cos(math.pi * progress))


def train(args) -> None:
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    device = get_device()

    use_bf16 = TRAIN_CONFIG.get("bf16", False) and torch.cuda.is_available()
    amp_ctx = torch.autocast("cuda", dtype=torch.bfloat16) if use_bf16 else torch.autocast("cpu", enabled=False)
    print(f"Mixed precision: {'bf16' if use_bf16 else 'fp32'}")

    # Linux/Docker: use multiple workers; MPS (mac): must be 0
    n_workers = 2 if torch.cuda.is_available() else 0

    print("Loading dataset …")
    print(f"  training data: {TRAIN_DATA.name}")
    train_loader = make_loader(
        TRAIN_DATA, SP_MODEL,
        batch_size=TRAIN_CONFIG["batch_size"],
        max_seq_len=TRAIN_CONFIG["max_seq_len"],
        shuffle=True, num_workers=n_workers,
    )
    valid_loader = make_loader(
        PROCESSED_DIR / "valid.txt", SP_MODEL,
        batch_size=TRAIN_CONFIG["batch_size"],
        max_seq_len=TRAIN_CONFIG["max_seq_len"],
        shuffle=False, num_workers=n_workers,
    )

    model = KeyboardLM(MODEL_CONFIG).to(device)
    print(f"Model params: {model.n_params:,}")

    # torch.compile (Inductor/Triton) speeds up the GPU forward/backward.
    # On ROCm it can be flaky on first use — set COMPILE=0 to disable.
    if os.environ.get("COMPILE", "1") != "0":
        try:
            model = torch.compile(model)
            print("Using torch.compile (Inductor)")
        except Exception as e:
            print(f"torch.compile failed, using eager mode: {e}")

    optimizer = AdamW(
        model.parameters(),
        lr=TRAIN_CONFIG["lr"],
        weight_decay=TRAIN_CONFIG["weight_decay"],
        betas=(0.9, 0.95),
    )

    total_steps = len(train_loader) * TRAIN_CONFIG["epochs"]
    if MAX_STEPS:
        total_steps = min(total_steps, MAX_STEPS)
    step = 0
    best_val_loss = float("inf")

    for epoch in range(1, TRAIN_CONFIG["epochs"] + 1):
        model.train()
        t0 = time.time()
        epoch_loss = 0.0

        for batch_idx, (x, y) in enumerate(train_loader):
            x = x.to(device, non_blocking=True)
            y = y.to(device, non_blocking=True)

            # Update LR
            lr = cosine_lr(step, TRAIN_CONFIG["warmup_steps"], total_steps,
                           TRAIN_CONFIG["lr"], TRAIN_CONFIG["min_lr"])
            for pg in optimizer.param_groups:
                pg["lr"] = lr

            with amp_ctx:
                _, loss = model(x, targets=y)

            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), TRAIN_CONFIG["grad_clip"])
            optimizer.step()

            epoch_loss += loss.item()
            step += 1

            if step % TRAIN_CONFIG["log_every"] == 0:
                elapsed = time.time() - t0
                print(f"epoch={epoch} step={step} loss={loss.item():.4f} "
                      f"lr={lr:.2e} time={elapsed:.1f}s")

            if step % TRAIN_CONFIG["save_every"] == 0:
                ckpt = out_dir / f"step_{step:07d}.pt"
                torch.save({"step": step, "model": model.state_dict(),
                            "config": MODEL_CONFIG, "optimizer": optimizer.state_dict()}, ckpt)
                print(f"[checkpoint] {ckpt}")

            if MAX_STEPS and step >= MAX_STEPS:
                break

        # Validation
        model.eval()
        val_loss = 0.0
        with torch.no_grad():
            for x, y in valid_loader:
                x = x.to(device, non_blocking=True)
                y = y.to(device, non_blocking=True)
                with amp_ctx:
                    _, loss = model(x, targets=y)
                val_loss += loss.item()
        val_loss /= len(valid_loader)
        print(f"[epoch {epoch}] val_loss={val_loss:.4f}")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            best_ckpt = out_dir / "best.pt"
            torch.save({"step": step, "model": model.state_dict(),
                        "config": MODEL_CONFIG}, best_ckpt)
            print(f"[best] val_loss={best_val_loss:.4f} → {best_ckpt}")

        if MAX_STEPS and step >= MAX_STEPS:
            print(f"Reached KEYBOARD_MAX_STEPS={MAX_STEPS}, stopping.")
            break

    print("Training complete.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    train(parser.parse_args())
